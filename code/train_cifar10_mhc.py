class StreamBlock(nn.Module):
    def __init__(self, d: int, mlp_ratio: int = 2, dropout: float = 0.0):
        super().__init__()
        hidden = int(d * mlp_ratio)
        self.ln = nn.LayerNorm(d)
        self.fc1 = nn.Linear(d, hidden)
        self.fc2 = nn.Linear(hidden, d)
        self.dropout = nn.Dropout(dropout)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        h = self.ln(x)
        h = self.fc1(h)
        h = F.gelu(h)
        h = self.dropout(h)
        h = self.fc2(h)
        h = self.dropout(h)
        return x + h


class MixerLayer(nn.Module):
    def __init__(self, n_streams: int, d: int, mixer: nn.Module):
        super().__init__()
        self.block = StreamBlock(d=d)
        self.mixer = mixer

    def forward(self, x: torch.Tensor) -> Tuple[torch.Tensor, torch.Tensor]:
        x = self.block(x)
        A = self.mixer()  # [n,n]
        x = torch.einsum("ij,bjd->bid", A, x)
        return x, A


class CIFARStem(nn.Module):
    def __init__(self, d: int, n_streams: int):
        super().__init__()
        self.conv = nn.Sequential(
            nn.Conv2d(3, 64, kernel_size=3, padding=1),
            nn.ReLU(inplace=True),
            nn.Conv2d(64, 128, kernel_size=3, padding=1),
            nn.ReLU(inplace=True),
            nn.MaxPool2d(2),  # 16x16
            nn.Conv2d(128, 256, kernel_size=3, padding=1),
            nn.ReLU(inplace=True),
            nn.MaxPool2d(2),  # 8x8
        )
        self.proj = nn.Linear(256 * 8 * 8, n_streams * d)
        self.n_streams = int(n_streams)
        self.d = int(d)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        h = self.conv(x).flatten(1)
        h = self.proj(h).view(h.shape[0], self.n_streams, self.d)
        return h


class MixerNet(nn.Module):
    def __init__(
        self,
        n_streams: int,
        d: int,
        depth: int,
        num_classes: int,
        mixer_factory,
    ):
        super().__init__()
        self.stem = CIFARStem(d=d, n_streams=n_streams)
        self.layers = nn.ModuleList([
            MixerLayer(n_streams=n_streams, d=d, mixer=mixer_factory())
            for _ in range(int(depth))
        ])
        self.head_ln = nn.LayerNorm(d)
        self.head = nn.Linear(d, num_classes)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        x = self.stem(x)  # [B, n, d]
        for layer in self.layers:
            x, _ = layer(x)
        x = self.head_ln(x).mean(dim=1)
        return self.head(x)


def unwrap_model(m: nn.Module) -> nn.Module:
    return m.module if isinstance(m, nn.DataParallel) else m


@torch.no_grad()
def stack_mixer_metrics(mats: List[torch.Tensor]) -> Dict[str, float]:
    """
    Diagnostics for the realized depth-wise mixer stack.

    For nonnegative mixers, the exact backward gain ||H_L ... H_1||_1 is
    computed by vector propagation w <- H^T w, which is the exact certificate
    noted in the theory text. The product certificate is the looser but
    compositional prod_l(1 + eps_c_l).
    """
    if not mats:
        return {
            "max_eps_c": float("nan"),
            "max_eps_r": float("nan"),
            "cert_bound": float("nan"),
            "log_cert": float("nan"),
            "exact_T1": float("nan"),
            "cert_ratio": float("nan"),
            "max_layer_H1": float("nan"),
        }

    mats64 = [A.detach().to(dtype=torch.float64, device="cpu") for A in mats]
    n = mats64[0].shape[0]
    ones = torch.ones(n, dtype=torch.float64)

    eps_c: List[float] = []
    eps_r: List[float] = []
    max_layer_h1 = 0.0
    for A in mats64:
        eps_c.append(float((A.sum(dim=0) - ones).abs().max().item()))
        eps_r.append(float((A.sum(dim=1) - ones).abs().max().item()))
        max_layer_h1 = max(max_layer_h1, float(A.abs().sum(dim=0).max().item()))

    log_cert = float(sum(math.log1p(e) for e in eps_c))
    cert_bound = float(math.exp(log_cert)) if log_cert < 700 else float("inf")

    w = torch.ones(n, dtype=torch.float64)
    for A in reversed(mats64):
        w = A.T @ w
    exact_t1 = float(w.abs().max().item())

    return {
        "max_eps_c": float(max(eps_c)),
        "max_eps_r": float(max(eps_r)),
        "cert_bound": cert_bound,
        "log_cert": log_cert,
        "exact_T1": exact_t1,
        "cert_ratio": exact_t1 / cert_bound if cert_bound > 0 else float("nan"),
        "max_layer_H1": max_layer_h1,
    }


@torch.no_grad()
def rho_star_from_doubly_stochastic(A: torch.Tensor) -> float:
    vals = torch.linalg.svdvals(A.detach().to(dtype=torch.float64, device="cpu"))
    vals, _ = torch.sort(vals, descending=True)
    if vals.numel() < 2:
        return 0.0
    return float((vals[1] ** 2).item())


@torch.no_grad()
def sinkhorn_step_ratio(mixer: SinkhornMixer) -> float:
    """
    Empirical epsilon_c(t+1) / epsilon_c(t) for the final two usable full steps.
    This is the finite-step counterpart of the local rho_* predictor.
    """
    X = mixer._positive().detach()
    ratios: List[float] = []
    prev: Optional[float] = None
    safe_eps = 1e-20
    for _ in range(int(mixer.t_max)):
        X = X / X.sum(dim=0, keepdim=True).clamp_min(safe_eps)
        X = X / X.sum(dim=1, keepdim=True).clamp_min(safe_eps)
        _er, ec = _marginal_errors(X)
        if prev is not None and prev > 1e-12 and ec > 1e-16:
            ratios.append(float(ec / prev))
        prev = float(ec)
    return float(ratios[-1]) if ratios else float("nan")


