@torch.no_grad()
def accuracy(logits: torch.Tensor, y: torch.Tensor) -> float:
    return (logits.argmax(dim=1) == y).float().mean().item()


def percentiles(x: List[float], ps=(25, 50, 75)) -> Tuple[float, float, float]:
    a = np.array(x, dtype=float)
    q = np.percentile(a, ps)
    return float(q[0]), float(q[1]), float(q[2])


def train_one_epoch_paired(
    soft: nn.Module,
    sink: nn.Module,
    loader: DataLoader,
    opt_soft: torch.optim.Optimizer,
    opt_sink: torch.optim.Optimizer,
    device: torch.device,
    *,
    amp: bool,
    max_batches: Optional[int] = None,
) -> Tuple[Tuple[float, float], Tuple[float, float]]:
    """
    One epoch where BOTH models see the exact same augmented minibatches.
    """
    soft.train(True)
    sink.train(True)

    scaler_soft = torch.cuda.amp.GradScaler(enabled=(amp and device.type == "cuda"))
    scaler_sink = torch.cuda.amp.GradScaler(enabled=(amp and device.type == "cuda"))

    tot_ls = tot_as = tot_ns = 0.0
    tot_lk = tot_ak = tot_nk = 0.0

    for batch_idx, (x, y) in enumerate(loader):
        if max_batches is not None and batch_idx >= int(max_batches):
            break
        x = x.to(device, non_blocking=True)
        y = y.to(device, non_blocking=True)
        bs = x.shape[0]

        # ---- Softmax model step ----
        opt_soft.zero_grad(set_to_none=True)
        with torch.cuda.amp.autocast(enabled=(amp and device.type == "cuda")):
            logits_s = soft(x)
            loss_s = F.cross_entropy(logits_s, y)
        if scaler_soft.is_enabled():
            scaler_soft.scale(loss_s).backward()
            scaler_soft.step(opt_soft)
            scaler_soft.update()
        else:
            loss_s.backward()
            opt_soft.step()

        with torch.no_grad():
            acc_s = accuracy(logits_s, y)
        tot_ls += float(loss_s.item()) * bs
        tot_as += float(acc_s) * bs
        tot_ns += bs

        # ---- Sinkhorn model step ----
        opt_sink.zero_grad(set_to_none=True)
        with torch.cuda.amp.autocast(enabled=(amp and device.type == "cuda")):
            logits_k = sink(x)
            loss_k = F.cross_entropy(logits_k, y)
        if scaler_sink.is_enabled():
            scaler_sink.scale(loss_k).backward()
            scaler_sink.step(opt_sink)
            scaler_sink.update()
        else:
            loss_k.backward()
            opt_sink.step()

        with torch.no_grad():
            acc_k = accuracy(logits_k, y)
        tot_lk += float(loss_k.item()) * bs
        tot_ak += float(acc_k) * bs
        tot_nk += bs

    return (tot_ls / tot_ns, tot_as / tot_ns), (tot_lk / tot_nk, tot_ak / tot_nk)


@torch.no_grad()
def eval_one_epoch(
    model: nn.Module,
    loader: DataLoader,
    device: torch.device,
    *,
    amp: bool,
    max_batches: Optional[int] = None,
) -> Tuple[float, float]:
    model.train(False)
    total_loss = 0.0
    total_acc = 0.0
    total_n = 0

    for batch_idx, (x, y) in enumerate(loader):
        if max_batches is not None and batch_idx >= int(max_batches):
            break
        x = x.to(device, non_blocking=True)
        y = y.to(device, non_blocking=True)
        with torch.cuda.amp.autocast(enabled=(amp and device.type == "cuda")):
            logits = model(x)
            loss = F.cross_entropy(logits, y)

        bs = x.shape[0]
        total_loss += float(loss.item()) * bs
        total_acc += float(accuracy(logits, y)) * bs
        total_n += bs

    return total_loss / total_n, total_acc / total_n


@torch.no_grad()
def collect_mixer_stats_soft(model: nn.Module) -> Dict[str, object]:
    m = unwrap_model(model)
    kappas: List[float] = []
    mats: List[torch.Tensor] = []
    for layer in m.layers:
        A = layer.mixer()
        mats.append(A)
        kappas.append(kappa_obs(A))
    q25, q50, q75 = percentiles(kappas, (25, 50, 75))
    stack = stack_mixer_metrics(mats)
    return {
        "kappas": kappas,
        "kappa_q25": q25,
        "kappa_med": q50,
        "kappa_q75": q75,
        **stack,
    }


@torch.no_grad()
def collect_mixer_stats_sinkhorn(model: nn.Module, eps_tol: float) -> Dict[str, object]:
    m = unwrap_model(model)
    kappas_early: List[float] = []
    kappas_fixed: List[float] = []
    t_stops: List[int] = []

    err_r_early: List[float] = []
    err_c_early: List[float] = []
    err_r_fixed: List[float] = []
    err_c_fixed: List[float] = []
    mats_early: List[torch.Tensor] = []
    rho_stars: List[float] = []
    step_ratios: List[float] = []

    hits = 0
    total = 0

    for layer in m.layers:
        assert isinstance(layer.mixer, SinkhornMixer)
        # Early-stop A
        A_early = layer.mixer()
        mats_early.append(A_early)
        kappas_early.append(kappa_obs(A_early))
        t_stops.append(int(layer.mixer.last_t_stop))
        er, ec = _marginal_errors(A_early)
        err_r_early.append(er)
        err_c_early.append(ec)
        total += 1
        if max(er, ec) <= float(eps_tol):
            hits += 1

        # Fixed-cap matrix using the same weights.
        A_fix = layer.mixer.sinkhorn_fixed()
        kappas_fixed.append(kappa_obs(A_fix))
        rho_stars.append(rho_star_from_doubly_stochastic(A_fix))
        step_ratios.append(sinkhorn_step_ratio(layer.mixer))
        er2, ec2 = _marginal_errors(A_fix)
        err_r_fixed.append(er2)
        err_c_fixed.append(ec2)

    q25e, q50e, q75e = percentiles(kappas_early, (25, 50, 75))
    q25f, q50f, q75f = percentiles(kappas_fixed, (25, 50, 75))
    stack = stack_mixer_metrics(mats_early)
    rho_arr = np.array(rho_stars, dtype=float)
    ratio_arr = np.array(step_ratios, dtype=float)
    ratio_arr = ratio_arr[np.isfinite(ratio_arr)]

    return {
        "kappas_early": kappas_early,
        "kappa_early_q25": q25e,
        "kappa_early_med": q50e,
        "kappa_early_q75": q75e,

        "kappas_fixed": kappas_fixed,
        "kappa_fixed_q25": q25f,
        "kappa_fixed_med": q50f,
        "kappa_fixed_q75": q75f,

        "t_stops": t_stops,
        "tstop_mean": float(np.mean(t_stops)) if t_stops else float("nan"),
        "tstop_med": float(np.median(t_stops)) if t_stops else float("nan"),
        "hit_rate": float(hits / max(total, 1)),

        "err_row_max": float(np.max(err_r_early)) if err_r_early else float("nan"),
        "err_col_max": float(np.max(err_c_early)) if err_c_early else float("nan"),
        "err_fixed_row_max": float(np.max(err_r_fixed)) if err_r_fixed else float("nan"),
        "err_fixed_col_max": float(np.max(err_c_fixed)) if err_c_fixed else float("nan"),
        "rho_star_median": float(np.nanmedian(rho_arr)) if rho_arr.size else float("nan"),
        "rho_star_mean": float(np.nanmean(rho_arr)) if rho_arr.size else float("nan"),
        "empirical_step_ratio_median": float(np.median(ratio_arr)) if ratio_arr.size else float("nan"),
        **stack,
    }


def make_model_pair(cfg: ProfileCfg, device: torch.device) -> Tuple[MixerNet, MixerNet]:
    def soft_factory():
        return SoftmaxMixer(
            n=cfg.n_streams,
            beta=cfg.beta_softmax,
            init_scale=cfg.init_scale,
            clip_logits=cfg.softmax_clip_logits,
        )

    def sink_factory():
        return SinkhornMixer(
            n=cfg.n_streams,
            beta=cfg.beta_sinkhorn,
            init_scale=cfg.init_scale,
            t_max=cfg.sinkhorn_t_max,
            eps_tol=cfg.sinkhorn_eps_tol,
            clip_logits=cfg.sinkhorn_clip_logits,
        )

    soft = MixerNet(cfg.n_streams, cfg.d, cfg.depth, 10, mixer_factory=soft_factory)
    sink = MixerNet(cfg.n_streams, cfg.d, cfg.depth, 10, mixer_factory=sink_factory)

    # Paired init: copy everything except mixer params.
    soft_sd = soft.state_dict()
    sink_sd = sink.state_dict()
    for k, v in soft_sd.items():
        if ".mixer." in k:
            continue
        if k in sink_sd and sink_sd[k].shape == v.shape:
            sink_sd[k] = v.clone()
    sink.load_state_dict(sink_sd)

    return soft.to(device), sink.to(device)


