def set_global_seed(
    seed: int,
    *,
    cudnn_deterministic: bool = False,
    deterministic_algorithms: bool = False,
    disable_tf32: bool = False,
) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)

    if disable_tf32:
        try:
            torch.backends.cuda.matmul.allow_tf32 = False
            torch.backends.cudnn.allow_tf32 = False
        except Exception:
            pass

    if cudnn_deterministic:
        torch.backends.cudnn.deterministic = True
        torch.backends.cudnn.benchmark = False

    if deterministic_algorithms:
        torch.use_deterministic_algorithms(True)
    else:
        try:
            torch.use_deterministic_algorithms(False)
        except Exception:
            pass


def seed_worker(worker_id: int) -> None:
    # Deterministic RNG per worker derived from base torch seed.
    worker_seed = torch.initial_seed() % 2**32
    np.random.seed(worker_seed)
    random.seed(worker_seed)


class EpochShuffleSampler(Sampler[int]):
    """
    Deterministic shuffling per epoch:
      perm(epoch) generated by torch.Generator seeded with (base_seed + epoch).
    """
    def __init__(self, data_source, base_seed: int, shuffle: bool = True) -> None:
        self.data_source = data_source
        self.base_seed = int(base_seed)
        self.shuffle = bool(shuffle)
        self.epoch = 0

    def set_epoch(self, epoch: int) -> None:
        self.epoch = int(epoch)

    def __iter__(self) -> Iterable[int]:
        n = len(self.data_source)
        if not self.shuffle:
            return iter(range(n))
        g = torch.Generator()
        g.manual_seed(self.base_seed + self.epoch)
        perm = torch.randperm(n, generator=g).tolist()
        return iter(perm)

    def __len__(self) -> int:
        return len(self.data_source)


