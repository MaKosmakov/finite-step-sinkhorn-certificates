def plot_epoch_metric(
    out_path: str,
    rows: List[EpochLog],
    field: str,
    ylabel: str,
    title: str,
    *,
    show: bool,
    logy: bool = False,
) -> None:
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    methods = sorted({r.model_type for r in rows})
    plt.figure()
    for method in methods:
        method_rows = [r for r in rows if r.model_type == method]
        epochs = sorted({r.epoch for r in method_rows})
        xs, means, stds = [], [], []
        for epoch in epochs:
            vals = np.array([float(getattr(r, field)) for r in method_rows if r.epoch == epoch], dtype=float)
            vals = vals[np.isfinite(vals)]
            if vals.size == 0:
                continue
            xs.append(epoch + 1)
            means.append(float(vals.mean()))
            stds.append(float(vals.std()))
        if not xs:
            continue
        xs_arr = np.array(xs)
        mu = np.array(means)
        sd = np.array(stds)
        plt.plot(xs_arr, mu, marker="o", label=method)
        if len(xs_arr) > 1:
            lo = np.maximum(mu - sd, 1e-16 if logy else -np.inf)
            hi = mu + sd
            plt.fill_between(xs_arr, lo, hi, alpha=0.18)
    plt.xlabel("epoch")
    plt.ylabel(ylabel)
    plt.title(title)
    if logy:
        plt.yscale("log")
    plt.legend()
    plt.tight_layout()
    plt.savefig(out_path, dpi=200)
    if show:
        plt.show()
    plt.close()


