@torch.no_grad()
def _marginal_errors(A: torch.Tensor) -> Tuple[float, float]:
    """
    Max absolute deviation from 1 for row sums and column sums.
    """
    n = A.shape[0]
    ones = torch.ones((n,), device=A.device, dtype=A.dtype)
    rs = A.sum(dim=1)
    cs = A.sum(dim=0)
    er = (rs - ones).abs().max().item()
    ec = (cs - ones).abs().max().item()
    return float(er), float(ec)


def finite_sinkhorn(
    M: torch.Tensor,
    t_max: int,
    eps_tol: float,
    *,
    early_stop: bool,
    safe_eps: float = 1e-20,
) -> Tuple[torch.Tensor, int]:
    """
    Finite-step Sinkhorn-Knopp scaling on positive matrices (M is [n,n]).
    Alternating col then row normalization.

    If early_stop=True: stop when both row/col errors <= eps_tol.
    If early_stop=False: always run exactly t_max steps for fixed-cap diagnostics.

    Returns:
      A: scaled matrix
      t_used: steps used (<= t_max if early_stop else == t_max)
    """
    X = M
    t_used = 0

    if early_stop:
        # Check initial errors cheaply.
        with torch.no_grad():
            er, ec = _marginal_errors(X)
            if max(er, ec) <= eps_tol:
                return X, 0

    for t in range(int(t_max)):
        col = X.sum(dim=0, keepdim=True).clamp_min(safe_eps)
        X = X / col
        row = X.sum(dim=1, keepdim=True).clamp_min(safe_eps)
        X = X / row
        t_used = t + 1

        if early_stop:
            with torch.no_grad():
                er, ec = _marginal_errors(X)
                if max(er, ec) <= eps_tol:
                    break

    return X, int(t_used)


