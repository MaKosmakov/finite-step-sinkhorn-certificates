class SoftmaxMixer(nn.Module):
    """
    Row-stochastic mixer: A = softmax(clipped(beta * W), dim=1).
    """
    def __init__(
        self,
        n: int,
        beta: float = 1.0,
        init_scale: float = 1.0,
        clip_logits: float = 10.0,
    ):
        super().__init__()
        self.n = int(n)
        self.beta = float(beta)
        self.clip_logits = float(clip_logits)
        self.W = nn.Parameter(torch.empty(n, n))
        nn.init.normal_(self.W, mean=0.0, std=init_scale / math.sqrt(n))

    def forward(self) -> torch.Tensor:
        z = self.beta * self.W
        if self.clip_logits > 0:
            z = z.clamp(-self.clip_logits, self.clip_logits)
        return F.softmax(z, dim=1)


class SinkhornMixer(nn.Module):
    """
    Positive -> finite Sinkhorn -> approximately doubly-stochastic.
    Uses exp(clipped(beta*W)) for positivity and numeric safety.

    During forward, this mixer runs early-stopped Sinkhorn. Fixed-cap diagnostics
    are evaluated separately via sinkhorn_fixed().
    """
    def __init__(
        self,
        n: int,
        beta: float = 1.0,
        init_scale: float = 1.0,
        t_max: int = 80,
        eps_tol: float = 5e-4,
        clip_logits: float = 10.0,
    ):
        super().__init__()
        self.n = int(n)
        self.beta = float(beta)
        self.t_max = int(t_max)
        self.eps_tol = float(eps_tol)
        self.clip_logits = float(clip_logits)
        self.W = nn.Parameter(torch.empty(n, n))
        nn.init.normal_(self.W, mean=0.0, std=init_scale / math.sqrt(n))

        # Non-parameter diagnostics (last forward call)
        self.last_t_stop: int = 0

    def _positive(self) -> torch.Tensor:
        z = self.beta * self.W
        if self.clip_logits > 0:
            z = z.clamp(-self.clip_logits, self.clip_logits)
        return torch.exp(z)

    def forward(self) -> torch.Tensor:
        M = self._positive()
        A, t_used = finite_sinkhorn(M, self.t_max, self.eps_tol, early_stop=True)
        self.last_t_stop = int(t_used)
        return A

    @torch.no_grad()
    def sinkhorn_fixed(self) -> torch.Tensor:
        """
        Same positive matrix, re-evaluated with exactly t_max steps.
        """
        M = self._positive()
        A, _ = finite_sinkhorn(M, self.t_max, self.eps_tol, early_stop=False)
        return A


