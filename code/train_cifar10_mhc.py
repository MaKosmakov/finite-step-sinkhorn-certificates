def plot_kappa_obs(
    out_path: str,
    all_kappas_soft: List[List[float]],
    all_kappas_sink_early: List[List[float]],
    all_kappas_sink_fixed: List[List[float]],
    title: str,
    show: bool,
    logy: bool,
) -> None:
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    if not all_kappas_soft or not all_kappas_sink_early or not all_kappas_sink_fixed:
        return

    def layerwise_stats(all_kappas: List[List[float]]):
        depth = len(all_kappas[0])
        med, q25, q75 = [], [], []
        for l in range(depth):
            vals = np.array([kk[l] for kk in all_kappas], float)
            q = np.percentile(vals, [25, 50, 75])
            q25.append(q[0]); med.append(q[1]); q75.append(q[2])
        return np.array(q25), np.array(med), np.array(q75)

    q25s, meds, q75s = layerwise_stats(all_kappas_soft)
    q25e, mede, q75e = layerwise_stats(all_kappas_sink_early)
    q25f, medf, q75f = layerwise_stats(all_kappas_sink_fixed)

    plt.figure()
    x = np.arange(1, len(meds) + 1)
    plt.plot(x, meds, label="softmax (median)")
    plt.fill_between(x, q25s, q75s, alpha=0.2)

    plt.plot(x, mede, label="sinkhorn-early (median)")
    plt.fill_between(x, q25e, q75e, alpha=0.2)

    plt.plot(x, medf, label="sinkhorn-fixed (median)")
    plt.fill_between(x, q25f, q75f, alpha=0.2)

    plt.xlabel("Layer")
    plt.ylabel(r"$\kappa_{\mathrm{obs}}=\max(A)/\min(A)$")
    plt.title(title + (" [log-y]" if logy else ""))
    if logy:
        plt.yscale("log")
    plt.legend()
    plt.tight_layout()
    plt.savefig(out_path, dpi=200)
    if show:
        plt.show()
    plt.close()


