def _is_within_directory(directory: str, target: str) -> bool:
    abs_directory = os.path.abspath(directory)
    abs_target = os.path.abspath(target)
    return os.path.commonpath([abs_directory]) == os.path.commonpath([abs_directory, abs_target])


def _safe_extract(tf: tarfile.TarFile, path: str) -> None:
    for member in tf.getmembers():
        member_path = os.path.join(path, member.name)
        if not _is_within_directory(path, member_path):
            raise RuntimeError("Blocked path traversal attempt in tarfile.")
    tf.extractall(path=path)


def maybe_extract_tarball(data_tarball: Optional[str], extract_root: str) -> None:
    if not data_tarball:
        return
    data_tarball = os.path.expanduser(data_tarball)
    extract_root = os.path.expanduser(extract_root)
    os.makedirs(extract_root, exist_ok=True)
    if os.path.isdir(os.path.join(extract_root, "cifar-10-batches-py")):
        return
    if not os.path.isfile(data_tarball):
        raise FileNotFoundError(f"data_tarball not found: {data_tarball}")
    with tarfile.open(data_tarball, "r:*") as tf:
        _safe_extract(tf, extract_root)


def get_cifar10_loaders(
    batch_size: int,
    num_workers: int,
    base_seed: int,
    data_root: str,
) -> Tuple[DataLoader, DataLoader, EpochShuffleSampler]:
    data_root = os.path.expanduser(data_root)
    os.makedirs(data_root, exist_ok=True)

    tr = T.Compose([
        T.RandomCrop(32, padding=4),
        T.RandomHorizontalFlip(),
        T.ToTensor(),
        T.Normalize((0.4914, 0.4822, 0.4465), (0.2470, 0.2435, 0.2616)),
    ])
    te = T.Compose([
        T.ToTensor(),
        T.Normalize((0.4914, 0.4822, 0.4465), (0.2470, 0.2435, 0.2616)),
    ])

    train_ds = load_cifar10(data_root, train=True, transform=tr)
    test_ds = load_cifar10(data_root, train=False, transform=te)

    sampler = EpochShuffleSampler(train_ds, base_seed=base_seed, shuffle=True)

    g = torch.Generator()
    g.manual_seed(base_seed)

    train_loader = DataLoader(
        train_ds,
        batch_size=batch_size,
        sampler=sampler,
        num_workers=num_workers,
        pin_memory=True,
        worker_init_fn=seed_worker,
        generator=g,
        persistent_workers=(num_workers > 0),
    )
    test_loader = DataLoader(
        test_ds,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=True,
        worker_init_fn=seed_worker,
        generator=g,
        persistent_workers=(num_workers > 0),
    )
    return train_loader, test_loader, sampler


