@dataclass
class ProfileCfg:
    name: str
    n_streams: int = 8
    d: int = 128
    depth: int = 128

    beta_softmax: float = 5.0
    beta_sinkhorn: float = 3.0
    init_scale: float = 2.5

    sinkhorn_t_max: int = 80
    sinkhorn_eps_tol: float = 5e-4
    sinkhorn_clip_logits: float = 10.0
    softmax_clip_logits: float = 10.0

    lr: float = 0.02
    weight_decay: float = 5e-4
    momentum: float = 0.9


def get_profile(profile: str) -> ProfileCfg:
    """
    Profiles are tuned for the paper narrative:
      - baseline: sanity / smoke test (faster)
      - stress_kappa: high beta/init to push kappa
      - stress_depth: very deep but milder kappa
      - stress_full: deep + high-kappa (paper stress regime)
    """
    p = str(profile).strip()

    if p == "baseline":
        return ProfileCfg(
            name="baseline",
            depth=32,
            beta_softmax=1.0,
            beta_sinkhorn=1.0,
            init_scale=1.0,
            sinkhorn_t_max=20,
            sinkhorn_eps_tol=1e-3,
            sinkhorn_clip_logits=10.0,
            softmax_clip_logits=10.0,
            lr=0.05,
        )

    if p == "stress_kappa":
        return ProfileCfg(
            name="stress_kappa",
            depth=32,
            beta_softmax=5.0,
            beta_sinkhorn=3.0,
            init_scale=2.5,
            sinkhorn_t_max=60,
            sinkhorn_eps_tol=5e-4,
            sinkhorn_clip_logits=10.0,
            softmax_clip_logits=10.0,
            lr=0.03,
        )

    if p == "stress_depth":
        return ProfileCfg(
            name="stress_depth",
            depth=128,
            beta_softmax=1.0,
            beta_sinkhorn=1.0,
            init_scale=1.0,
            sinkhorn_t_max=40,
            sinkhorn_eps_tol=1e-3,
            sinkhorn_clip_logits=10.0,
            softmax_clip_logits=10.0,
            lr=0.03,
        )

    if p == "stress_full":
        # Paper stress regime: deep and intentionally ill-conditioned softmax weights.
        # Sinkhorn cap is set so that eps_tol is typically met (or very nearly met) in <= t_max steps.
        return ProfileCfg(
            name="stress_full",
            depth=128,
            beta_softmax=5.0,
            beta_sinkhorn=3.0,
            init_scale=2.5,
            sinkhorn_t_max=80,
            sinkhorn_eps_tol=5e-4,
            sinkhorn_clip_logits=10.0,
            softmax_clip_logits=10.0,
            lr=0.02,
        )

    raise ValueError(f"Unknown profile: {profile}")


